#define FONT_WIDTH   7
#define FONT_HEIGHT 10
#define WHITE   0xFFFF
#define BLACK   0x0000

static void st7789_write_char(uint_fast16_t x, uint_fast16_t y, char ch)
{
    st7789_set_address_window(x, y, x + FONT_WIDTH - 1, y + FONT_HEIGHT - 1);

    for (uint_fast8_t i = 0; i < FONT_HEIGHT; i++)
    {
        uint_fast16_t b = font[(ch - 32) * FONT_HEIGHT + i];
        for (uint_fast8_t j = 0; j < FONT_WIDTH; j++)
        {
            if ((b << j) & 0x8000)
            {
                uint8_t data[] = {WHITE >> 8, WHITE & 0xFF};
                lcd_send_cmd(NULL, NULL, 0, data, sizeof(data));
            }
            else
            {
                uint8_t data[] = {BLACK >> 8, BLACK & 0xFF};
                lcd_send_cmd(NULL, NULL, 0, data, sizeof(data));
            }
        }
    }
}

static void st7789_write_string(uint_fast16_t x, uint_fast16_t y, const char *str)
{
    while (*str)
    {
        st7789_write_char(x, y, *str);
        x += FONT_WIDTH;
        str++;
    }
}

void print_line(const char *fmt, ...)
{
    static char buf[64];
    static uint_fast8_t y = 0;
    va_list args;
    va_start(args, fmt);
    vsprintf(buf, fmt, args);
    va_end(args);
    st7789_write_string(0, y, buf);
    y += 10;
}
